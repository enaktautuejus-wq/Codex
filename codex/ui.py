def _change_workspace(agent, config, registry, raw_path: str):
    raw_path = raw_path.strip()
    if not raw_path:
        return "Workspace saat ini: " + str(registry.ws.root)
    candidate = os.path.abspath(os.path.expanduser(raw_path))
    if not os.path.isdir(candidate):
        return f"Workspace tidak ditemukan atau bukan direktori: {candidate}"
    os.chdir(candidate)
    registry.ws = Workspace(candidate)
    registry.config = config
    registry.memory = __import__('codex.memory', fromlist=['MemoryStore']).MemoryStore(candidate)
    registry.project = ProjectIndex(candidate)
    registry.checkpoints = __import__('codex.checkpoint', fromlist=['Checkpoints']).Checkpoints(candidate)
    registry.project.scan()
    config.workspace = candidate
    agent.project_context = registry.project.compact_context()
    agent.messages.append({
        "role": "system",
        "content": f"Workspace aktif sekarang: {candidate}. Gunakan workspace ini untuk operasi file dan shell. Project context baru:\n{agent.project_context}",
    })
    return f"Workspace aktif: {candidate}"

def copy_text_to_clipboard(text: str) -> str:
    """Copy text using Termux API when available, otherwise OSC52."""
    exe = shutil.which("termux-clipboard-set")
    if exe:
        proc = subprocess.run([exe], input=text, text=True, capture_output=True, timeout=10)
        if proc.returncode == 0:
            return "Code berhasil disalin ke clipboard Termux."
    encoded = base64.b64encode(text.encode("utf-8")).decode("ascii")
    sys.stdout.write(f"\033]52;c;{encoded}\a")
    sys.stdout.flush()
    return "Kode dikirim ke clipboard terminal via OSC52 (jika terminal mendukungnya)."


def run_ui(agent, config, registry):
    clear()
    banner(config)
    last_answer = ""
    while True:
        try:
            text = input(f"{RED}root@codex:~#{RESET} ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if not text:
            continue
        if text in {"/exit", "/quit"}:
            break
        if text == "/clear":
            agent.messages = [{"role":"system","content":agent.messages[0]["content"]}]
            clear(); banner(config); continue
        if text == "/pwd":
            print(f"Workspace: {registry.ws.root}\n")
            continue
        if text.startswith("/copy"):
            parts=text.split(maxsplit=1)
            try: idx=int(parts[1]) if len(parts)>1 else 1
            except ValueError: idx=1
            blocks=extract_code_blocks(last_answer)
            if not blocks or idx < 1 or idx > len(blocks):
                print(f"{RED}Code block tidak ditemukan: {idx}{RESET}\n")
                continue
            print(copy_text_to_clipboard(blocks[idx-1]["code"]) + "\n")
            continue
        if text.startswith("/cd"):
            target = text[3:].strip()
            print(_change_workspace(agent, config, registry, target) + "\n")
            continue
        try:
            print(f"{CYAN}root@ai-codex:~#{RESET}")
            live = LiveMarkdownRenderer()
            streamed=[]
            def on_token(piece):
                streamed.append(piece)
                live.feed(piece)
            agent.stream_callback = on_token
            try:
                answer = agent.run(text)
            finally:
                agent.stream_callback = None
            last_answer = "".join(streamed) if streamed else answer
            if streamed:
                live.finish(answer)
            else:
                print(render_markdown(answer)); print()
        except Exception as exc:
            print(f"{RED}API/tool error:{RESET} {exc}\n")
